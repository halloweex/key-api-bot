"""The Rust pilot's access contract is what the app says now.

`rust/contract/access.json` is generated by `tests/rust_access_contract.py`
from `web.main.app`, and the pilot embeds it when it is built: which routes
exist, in the order Starlette tries them, which gates each one runs and in
what order, which limits it carries, what the matrix and the default tabs say.
A route added, a gate added or re-pointed at another tab, a limit changed — any
of them, and this fails, naming what moved.

The fix is never an edit of the JSON. Regenerate it
(`python -m tests.rust_access_contract`, Python 3.14), and let the pilot's
harness say whether Rust still answers as Python does.
"""
from __future__ import annotations

import json

import pytest

from tests.routes_helper import iter_endpoints
from tests.rust_access_contract import CONTRACT_PATH, _dependency, build, render


def _key(route):
    return (route["kind"], route.get("path"), tuple(route.get("methods", ())))


def _committed():
    return json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))


def test_the_committed_contract_is_what_the_app_says():
    committed, fresh = _committed(), build()
    if fresh == committed:
        return
    moved = [f"{key}: changed" for key in sorted(set(fresh) | set(committed))
             if key != "routes" and fresh.get(key) != committed.get(key)]
    old = {_key(r): r for r in committed.get("routes", [])}
    new = {_key(r): r for r in fresh["routes"]}
    moved += [f"added {k}" for k in new if k not in old]
    moved += [f"removed {k}" for k in old if k not in new]
    moved += [f"changed {k}: {old[k]} -> {new[k]}" for k in new if k in old and old[k] != new[k]]
    if not moved:
        moved.append("the same routes in another order, and the order is the match order")
    pytest.fail(
        "rust/contract/access.json no longer describes web.main.app. Regenerate it "
        "with `python -m tests.rust_access_contract` and run the pilot's harness:\n  "
        + "\n  ".join(moved[:40])
    )


def test_the_file_is_its_own_rendering():
    """A hand edit that keeps the values and changes the text is drift too."""
    text = CONTRACT_PATH.read_text(encoding="utf-8")
    assert render(json.loads(text)) == text


def test_the_export_sees_every_endpoint_an_independent_walk_sees():
    """`tests/routes_helper.py` walks the include tree by hand: the export,
    which reads FastAPI's effective contexts, must find the same endpoints
    and the same gates, or one of the two walks is blind to something."""
    from web.main import app

    exported = {}
    for route in _committed()["routes"]:
        if route["kind"] == "api":
            gates = {json.dumps(d, sort_keys=True) for d in route["dependencies"]}
            exported[(route["path"], tuple(route["methods"]))] = gates
    walked = {}
    for endpoint in iter_endpoints(app):
        if not endpoint.methods:
            continue                       # a WebSocket route: no HTTP methods
        gates = {json.dumps(_dependency(call), sort_keys=True) for call in endpoint.dependencies}
        walked[(endpoint.path, tuple(sorted(endpoint.methods)))] = gates
    assert set(exported) == set(walked)
    assert {k: v for k, v in exported.items() if v != walked[k]} == {}


def test_no_admin_id_is_written_into_the_contract():
    from core.permissions import ADMIN_USER_IDS

    text = CONTRACT_PATH.read_text(encoding="utf-8")
    assert [i for i in ADMIN_USER_IDS if str(i) in text] == []
