def _literal(value: object, indent: str) -> str:
    if isinstance(value, tuple):
        inner = indent + "    "
        items = "".join(f"{inner}{_literal(v, inner)},\n" for v in value)
        return f"(\n{items}{indent})"
    assert isinstance(value, str), type(value)
    lines = value.splitlines(keepends=True)
    if len(lines) <= 1:
        return repr(value)
    inner = indent + "    "
    return "(\n" + "".join(f"{inner}{line!r}\n" for line in lines) + f"{indent})"


def _source_with(renderings: Dict[str, object]) -> str:
    """This file with its literal block replaced by `renderings`."""
    begin = "# --- BEGIN LITERALS (generated by this module run as a script; do not edit) ---\n"
    end = "# --- END LITERALS ---\n"
    with open(__file__, encoding="utf-8") as handle:
        source = handle.read()
    head, rest = source.split(begin, 1)
    _, tail = rest.split(end, 1)
    body = "RENDERINGS: Dict[str, object] = {\n"
    for name, value in renderings.items():
        body += f"    {name!r}: {_literal(value, '    ')},\n"
    body += "}\n"
    return head + begin + body + end + tail


