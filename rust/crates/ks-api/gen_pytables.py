"""Regenerate the CPython facts the Rust pilot reproduces.

Run from the repository root, in the Python production runs and with the
locked dependencies — the tables are CPython's Unicode database, and the int
and bool cases are pydantic's, so a different interpreter or lock can answer
differently:

    docker run --rm -v "$PWD:/app" -w /app <python:3.14-slim + requirements-dev.lock> \
        python rust/crates/ks-api/gen_pytables.py

Writes two files beside this one, both deterministic (fixed seed):

- `src/pytables.rs` — which characters `str.isdecimal`, `str.isspace` and
  `str.isprintable` accept. The port needs them because `datetime.strptime`
  reads `%Y` with a Unicode `\\d`, `str.strip()` strips more than Rust's
  `trim()`, and `repr()` escapes what `isprintable` rejects.
- `tests/fixtures/python_semantics.jsonl` — inputs with CPython's answers:
  `round()`, builtin `sum()` (compensated since 3.12), `strptime`, `repr`,
  `lower().strip()`, and pydantic's lax int and bool parsing of a query
  string. `cargo test` checks the port against every line without Python.
"""
from __future__ import annotations

import json
import random
import struct
import sys
import unicodedata
from datetime import datetime
from decimal import Decimal
from pathlib import Path
from typing import Optional

HERE = Path(__file__).resolve().parent
MAX = sys.maxunicode


def _ranges(pred) -> list[tuple[int, int]]:
    out, start = [], None
    for cp in range(MAX + 1):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX))
    return out


def _decimal_zeros() -> list[int]:
    """The first code point of every run of ten decimal digits. `re`'s `\\d`
    on a str pattern is `str.isdecimal`, which is category Nd, and Unicode
    keeps every Nd digit in a contiguous 0..9 run — asserted, not assumed."""
    zeros = []
    for cp in range(MAX + 1):
        c = chr(cp)
        assert c.isdecimal() == (unicodedata.category(c) == "Nd"), hex(cp)
        if c.isdecimal() and unicodedata.decimal(c) == 0:
            for k in range(10):
                assert int(chr(cp + k)) == k, hex(cp + k)
            zeros.append(cp)
    assert sum(chr(cp).isdecimal() for cp in range(MAX + 1)) == 10 * len(zeros)
    return zeros


def _rust_tables() -> str:
    zeros = _decimal_zeros()
    space = [cp for cp in range(MAX + 1) if chr(cp).isspace()]
    # ASCII is handled in code; the table starts where `repr` consults it.
    unprintable = _ranges(lambda cp: cp >= 0x80 and not chr(cp).isprintable())

    def hexes(values, per_line=8):
        rows = []
        for i in range(0, len(values), per_line):
            rows.append("    " + " ".join(f"{v}," for v in values[i:i + per_line]))
        return "\n".join(rows)

    return f"""\
//! GENERATED by `gen_pytables.py` — do not edit by hand.
//!
//! CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.

/// First code point of each run of ten decimal digits (`str.isdecimal`).
pub const DECIMAL_ZEROS: &[u32] = &[
{hexes([f"0x{z:04X}" for z in zeros])}
];

/// Every code point `str.isspace` accepts — `str.strip()`'s set.
pub const WHITESPACE: &[u32] = &[
{hexes([f"0x{c:04X}" for c in space])}
];

/// Inclusive ranges, from U+0080 on, that `str.isprintable` rejects.
pub const NOT_PRINTABLE: &[(u32, u32)] = &[
{hexes([f"(0x{a:04X}, 0x{b:04X})" for a, b in unprintable], per_line=4)}
];
"""


def _bits(x: float) -> str:
    return f"{struct.unpack('<Q', struct.pack('<d', x))[0]:016x}"


def _num(v) -> dict:
    return {"i": v} if isinstance(v, int) else {"f": _bits(v)}


def _amount(rng: random.Random, cents_max: int) -> float:
    # What `float(Decimal)` makes of a NUMERIC(14,2): the payload's one input.
    return float(Decimal(rng.randint(0, cents_max)) / 100)


def _round_cases(rng: random.Random):
    xs = [_amount(rng, 99_999_999_999) for _ in range(400)]
    for _ in range(400):
        xs.append(sum(_amount(rng, 50_000_000) for _ in range(rng.randint(2, 62))))
    xs += [k / 8 for k in range(0, 4000, 11)]               # exact binary ties
    xs += [float(f"{rng.randint(0, 10**6)}.{d:02d}5") for d in range(100)]
    xs += [((a - b) / b) * 100 for a, b in
           ((_amount(rng, 10**9), _amount(rng, 10**9) or 1.0) for _ in range(300))]
    xs += [0.0, -0.0, 1e-9, -1e-9, 1e15 + 0.125, 2.675, 1.005, 0.285, -2.675]
    for x in xs:
        yield {"kind": "round", "x": _bits(x), "r2": _bits(round(x, 2)), "r1": _bits(round(x, 1))}


def _sum_cases(rng: random.Random):
    for _ in range(150):
        days = rng.randint(0, 40)
        items = [0 if rng.random() < 0.2 else _amount(rng, rng.choice((10**6, 10**8, 10**11)))
                 for _ in range(days)]
        yield {"kind": "sum", "items": [_num(v) for v in items], "result": _num(sum(items))}


_STRPTIME_FIXED = [
    "2026-1-5", "2026-01- 5", "٢٠٢٦-٠١-٠٥", "2026-1٥-01", "2026-01-1٥", "0005-01-01",
    "2026-02-30", "2026-13-01", "26-01-01", "2026-01-01T00:00", "2026-01-310", "2026-1-1",
    " 2026-01-01", "2026-01-01 ", "２０２６-01-01", "2026-001-01", "0000-01-01", "9999-12-31",
    "0001-01-01", "2024-02-29", "2025-02-29", "2026-1-31", "2026-04-31", "2026-10- 9",
    "2026-10-3", "2026-10-30", "2026-10-39", "2026-10-0", "2026-0-10", "2026-10-1 ", "",
    "2026", "2026-", "2026-10", "2026-10-", "2026/10/10", "2026-10-10\n", "2026-٠1-01",
]


def _strptime_cases(rng: random.Random):
    alphabet = "0123456789-- 1239٥２"
    fuzz = ["".join(rng.choice(alphabet) for _ in range(rng.randint(6, 11))) for _ in range(800)]
    structured = [f"{y}-{m}-{d}" for y in ("2026", "0999", "１９９９")
                  for m in ("1", "01", "10", "12", "13", "0", " 1")
                  for d in ("1", "01", " 1", "9", "29", "30", "31", "32", "1٥", "2٩", "3٥")]
    for s in _STRPTIME_FIXED + structured + fuzz:
        try:
            ok: Optional[str] = datetime.strptime(s, "%Y-%m-%d").date().isoformat()
        except ValueError:
            ok = None
        yield {"kind": "strptime", "s": s, "ok": ok}


_TEXTS = [
    "", "xyz", "it's", 'a"b', "a\"b'c", "x\ty", "back\\slash", "\n\r", "\x00\x1f\x7f", "день",
    "ДЕНЬ", "ΣΑΣ", "İstanbul", "\xa0bad", "bad\xa0", " ", "​", "", "\U0010ffff",
    "\x85", "\xad", "émoji 🙂", "͸", "  today  ", "today\x1f", "\x1c\x1d\x1e\x1fweek",
    "　month　", "WEEK", "Last_Week", "ß", "ﬁ", "́", "क्", "\x80\x9f", "؜",
]


def _text_cases():
    for s in _TEXTS:
        yield {"kind": "repr", "s": s, "repr": repr(s)}
        yield {"kind": "lower_strip", "s": s, "out": s.lower().strip()}


_INTS = [
    "1", " 1", "1 ", "+1", "-1", "01", "1.0", "1.00", "1.", "1.5", "1e0", "1_0", "1__0", "_1",
    "1_", "0x1", "١", "", " ", "abc", "1 1", "99999999999999999999", "-0", "+0", "１", "1_000",
    "-1_000.00", "+", "-", ".0", "0.", "4\t", " 4", "007", "-007", "2.000", "1_0.0",
    "9223372036854775807", "9223372036854775808", "-9223372036854775809", "3 ",
]
_BOOLS = ["true", "True", "TRUE", " true", "true ", "1", "0", "yes", "on", "off", "t", "f", "y",
          "n", "no", "maybe", "", "2", "YES", "Off", "fAlSe"]


def _pydantic_cases():
    from pydantic import TypeAdapter, ValidationError

    ints, bools = TypeAdapter(Optional[int]), TypeAdapter(Optional[bool])
    for s in _INTS:
        try:
            yield {"kind": "int", "s": s, "ok": str(ints.validate_python(s)), "error": None}
        except ValidationError as e:
            yield {"kind": "int", "s": s, "ok": None, "error": e.errors()[0]["type"]}
    for s in _BOOLS:
        try:
            yield {"kind": "bool", "s": s, "ok": bools.validate_python(s)}
        except ValidationError:
            yield {"kind": "bool", "s": s, "ok": None}


def main() -> None:
    (HERE / "src" / "pytables.rs").write_text(_rust_tables(), encoding="utf-8")
    rng = random.Random(20261021)
    records = [{"kind": "made_by", "python": sys.version.split()[0],
                "unicode": unicodedata.unidata_version}]
    for gen in (_round_cases(rng), _sum_cases(rng), _strptime_cases(rng), _text_cases(),
                _pydantic_cases()):
        records.extend(gen)
    out = HERE / "tests" / "fixtures" / "python_semantics.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records),
                   encoding="utf-8")
    print(f"{len(records)} records, CPython {sys.version.split()[0]}")


if __name__ == "__main__":
    main()
