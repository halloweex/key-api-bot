//! The port's CPython semantics, case by case, against CPython itself.
//!
//! `fixtures/python_semantics.jsonl` holds inputs and the answers CPython
//! 3.14 and the locked pydantic gave (`gen_pytables.py` writes it). Floats
//! are compared bit for bit: the harness compares JSON, and one ulp is a
//! different number in the response.

use std::collections::BTreeMap;

use ks_api::params::{lax_bool, lax_int};
use ks_api::pyrt::{PyNum, py_lower_strip, py_sum, repr_str, round_float};
use ks_api::strptime::strptime_ymd;
use serde_json::Value;

const FIXTURES: &str = include_str!("fixtures/python_semantics.jsonl");

fn float(v: &Value) -> f64 {
    let hex = v.as_str().expect("a float is its bits in hex");
    f64::from_bits(u64::from_str_radix(hex, 16).expect("sixteen hex digits"))
}

fn num(v: &Value) -> PyNum {
    match v.get("i") {
        Some(i) => PyNum::Int(i.as_i64().expect("an int")),
        None => PyNum::Float(float(&v["f"])),
    }
}

fn identical(a: PyNum, b: PyNum) -> bool {
    match (a, b) {
        (PyNum::Int(x), PyNum::Int(y)) => x == y,
        (PyNum::Float(x), PyNum::Float(y)) => x.to_bits() == y.to_bits(),
        _ => false,
    }
}

fn agrees(case: &Value) -> bool {
    let text = || case["s"].as_str().expect("a string input");
    match case["kind"].as_str().expect("a kind") {
        "made_by" => true,
        "round" => {
            let x = float(&case["x"]);
            round_float(x, 2).to_bits() == float(&case["r2"]).to_bits()
                && round_float(x, 1).to_bits() == float(&case["r1"]).to_bits()
        }
        "sum" => {
            let items: Vec<PyNum> = case["items"]
                .as_array()
                .expect("items")
                .iter()
                .map(num)
                .collect();
            identical(py_sum(&items), num(&case["result"]))
        }
        "strptime" => strptime_ymd(text()).map(|d| d.to_string()).as_deref() == case["ok"].as_str(),
        "repr" => repr_str(text()) == case["repr"].as_str().expect("a repr"),
        "lower_strip" => py_lower_strip(text()) == case["out"].as_str().expect("an output"),
        "int" => match lax_int(text()) {
            Ok(v) => case["ok"].as_str() == Some(v.repr().as_str()),
            Err(kind) => case["error"].as_str() == Some(kind),
        },
        "bool" => lax_bool(text()) == case["ok"].as_bool(),
        other => panic!("a fixture kind this test does not know: {other}"),
    }
}

#[test]
fn every_case_answers_as_cpython_did() {
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    let mut disagree = Vec::new();
    for line in FIXTURES.lines() {
        let case: Value = serde_json::from_str(line).expect("a JSON line");
        *seen
            .entry(case["kind"].as_str().unwrap_or("?").to_owned())
            .or_default() += 1;
        if !agrees(&case) {
            disagree.push(line);
        }
    }
    assert!(
        disagree.is_empty(),
        "{} case(s) answer differently from CPython, first ones:\n{}",
        disagree.len(),
        disagree
            .iter()
            .take(10)
            .copied()
            .collect::<Vec<_>>()
            .join("\n")
    );
    // The file is regenerated by hand; a kind that vanished would pass empty.
    for kind in [
        "round",
        "sum",
        "strptime",
        "repr",
        "lower_strip",
        "int",
        "bool",
    ] {
        assert!(
            seen.get(kind).copied().unwrap_or(0) >= 20,
            "too few {kind} cases: {seen:?}"
        );
    }
}
