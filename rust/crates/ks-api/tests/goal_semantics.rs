//! The goal arithmetic, case by case, against CPython itself.
//!
//! `fixtures/goal_semantics.jsonl` holds inputs and the answers CPython 3.14
//! gave (`gen_goal_fixtures.py` writes it): `round()` to an int,
//! `_recency_weighted`, `_growth_cap`, and whole smart goals —
//! `generate_smart_goals` itself, its reads answered with the line's numbers,
//! as the bytes orjson wrote. Floats are compared bit for bit, smart goals
//! byte for byte.

use std::collections::BTreeMap;
use std::str::FromStr;

use chrono::{DateTime, Utc};
use ks_api::goals::{Inputs, compose_json, growth_cap_of, recency_weighted, round_int};
use ks_api::gold::decimal_to_float;
use ks_api::pyrt::PyNum;
use rust_decimal::Decimal;
use serde_json::Value;

const FIXTURES: &str = include_str!("fixtures/goal_semantics.jsonl");

fn float(v: &Value) -> f64 {
    let hex = v.as_str().expect("a float is its bits in hex");
    f64::from_bits(u64::from_str_radix(hex, 16).expect("sixteen hex digits"))
}

fn opt_float(v: &Value) -> Option<f64> {
    (!v.is_null()).then(|| float(v))
}

fn num(v: &Value) -> PyNum {
    match v.get("i") {
        Some(i) => PyNum::Int(i.as_i64().expect("an int")),
        None => PyNum::Float(float(&v["f"])),
    }
}

/// A numeric as asyncpg hands it to Python, and the port to `float()`.
fn decimal(v: &Value) -> Option<f64> {
    v.as_str()
        .map(|s| decimal_to_float(Decimal::from_str(s).expect("a decimal")))
}

fn smart(case: &Value) -> Vec<u8> {
    let seasonal = case["seasonal"].as_array().map(|s| {
        (
            decimal(&s[0]),
            decimal(&s[1]),
            decimal(&s[2]),
            s[3].as_str().map(str::to_owned),
        )
    });
    let growth = case["growth"]["row"]
        .as_bool()
        .expect("a flag")
        .then(|| decimal(&case["growth"]["value"]));
    let weekly = case["weekly"]
        .as_array()
        .expect("weeks")
        .iter()
        .map(|w| {
            (
                w[0].as_i64().expect("a week"),
                decimal(&w[1]).expect("a weight"),
            )
        })
        .collect();
    let now: DateTime<Utc> = DateTime::parse_from_rfc3339("2026-10-21T09:00:00Z")
        .expect("an instant")
        .with_timezone(&Utc);
    compose_json(
        Inputs {
            year: case["year"].as_i64().expect("a year"),
            month: case["month"].as_i64().expect("a month"),
            ml: float(&case["ml"]),
            cap: float(&case["cap"]),
            last_year: num(&case["last_year"]),
            recent: num(&case["recent"]),
            seasonal,
            growth,
            weekly,
        },
        now,
    )
}

fn agrees(case: &Value) -> bool {
    match case["kind"].as_str().expect("a kind") {
        "made_by" => true,
        "round_int" => Some(round_int(float(&case["x"]))) == case["i"].as_i64(),
        "recency" => {
            let rates: Vec<f64> = case["rates"]
                .as_array()
                .expect("rates")
                .iter()
                .map(float)
                .collect();
            recency_weighted(&rates).to_bits() == float(&case["out"]).to_bits()
        }
        "growth_cap" => {
            growth_cap_of(
                opt_float(&case["avg"]),
                opt_float(&case["std"]),
                case["count"].as_i64().expect("a count"),
            )
            .to_bits()
                == float(&case["out"]).to_bits()
        }
        "smart" => smart(case) == case["json"].as_str().expect("bytes").as_bytes(),
        other => panic!("a fixture kind this test does not know: {other}"),
    }
}

#[test]
fn every_case_answers_as_cpython_did() {
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    let mut disagree = Vec::new();
    for line in FIXTURES.lines() {
        let case: Value = serde_json::from_str(line).expect("a JSON line");
        *seen
            .entry(case["kind"].as_str().unwrap_or("?").to_owned())
            .or_default() += 1;
        if !agrees(&case) {
            disagree.push(line);
        }
    }
    assert!(
        disagree.is_empty(),
        "{} case(s) answer differently from CPython, first ones:\n{}",
        disagree.len(),
        disagree
            .iter()
            .take(5)
            .copied()
            .collect::<Vec<_>>()
            .join("\n")
    );
    // The file is regenerated by hand; a kind that vanished would pass empty.
    for kind in ["round_int", "recency", "growth_cap", "smart"] {
        assert!(
            seen.get(kind).copied().unwrap_or(0) >= 100,
            "too few {kind} cases: {seen:?}"
        );
    }
}
